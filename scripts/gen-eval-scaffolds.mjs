// Generates each eval case's scaffold.sh from its seed.json.
//
// A seed declares where the case starts: the storefront repository, plus
// optionally a saved model, an active change at some stage, and code built
// for it. This script prepares that workspace in a temporary directory,
// using the same helpers as the integration tests, and writes it out as one
// self-contained Bash script (claude plugin eval runs scaffolds with nothing
// but PATH and HOME). `--check` fails when a committed scaffold is stale.
//
// seed.json:
//   {
//     "model": true,                          save fixtures/storefront.model.json
//     "change": {                             an active change set
//       "status": "draft" | "in-review" | "approved" | "implemented",
//       "ops": "fraud" | "none",
//       "intent": true,
//       "questions": "none" | "open" | "answered",
//       "plan": true
//     },
//     "implement": "complete" | "forget-hold"  code built for the change, left uncommitted
//   }

import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import { answerQuestion, addQuestions, approve, savePlan, setIntent, setOps, submit, markImplemented, newChangeSet } from '../plugins/sysedit/core/changeset.ts'
import { FRAUD_INTENT, FRAUD_OPS, fraudQuestions, goldenModel, implementFraudCheck } from '../tests/helpers/fixture.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const evalsDir = join(root, 'plugins', 'sysedit', 'evals')
const check = process.argv.includes('--check')
const NOW = '2026-10-01T09:00:00.000Z'
const HEAD = '__SYSEDIT_HEAD__'

const unwrap = r => {
  if (!r.ok) throw new Error(r.reason)
  return r.value
}

function buildChange(seed) {
  let cs = newChangeSet({
    id: '0001-fraud-check',
    title: 'Fraud check before capture',
    base: HEAD,
    request: 'Add a fraud check before we capture payment.',
    flow: 'checkout',
    risk: 'high',
    now: NOW,
  })
  if (seed.ops !== 'none') cs = unwrap(setOps(cs, FRAUD_OPS, NOW, 'engineer'))
  if (seed.intent !== false) cs = unwrap(setIntent(cs, FRAUD_INTENT, NOW))
  if (seed.status === 'draft') return cs
  cs = unwrap(submit(cs, NOW))
  if (seed.questions && seed.questions !== 'none') {
    cs = unwrap(addQuestions(cs, fraudQuestions(), NOW)).cs
    if (seed.questions === 'answered' || ['approved', 'implemented'].includes(seed.status)) {
      cs = unwrap(answerQuestion(cs, { questionId: 'q2', optionId: 'closed', quote: 'fail closed' }, NOW))
      // An answer the map can express (it adds OrderHold.create -> InventoryService.release), so the plan can build it.
      cs = unwrap(answerQuestion(cs, { questionId: 'q3', optionId: 'release', quote: 'release the stock as soon as the order is held' }, NOW))
    }
  }
  if (seed.status === 'in-review') return cs
  cs = unwrap(approve(cs, NOW))
  if (seed.plan) {
    cs = unwrap(
      savePlan(
        cs,
        [
          { id: 't1', title: 'FraudService.score and the call from placeOrder', ops: [0, 1, 4, 5], files: ['src/fraud/service.ts', 'src/checkout/service.ts'], answers: ['q2'] },
          { id: 't2', title: 'OrderHold.create for risky orders', ops: [2, 3, ...cs.ops.map((_, i) => i).filter(i => i > 5)], files: ['src/orders/hold.ts', 'src/checkout/service.ts'], answers: ['q2', 'q3'] },
        ],
        NOW,
      ),
    )
  }
  if (seed.status === 'approved') return cs
  return unwrap(markImplemented(cs, NOW))
}

function listFiles(dir) {
  return readdirSync(dir, { recursive: true })
    .map(String)
    .filter(f => statSync(join(dir, f)).isFile())
    .sort()
}

function heredoc(path, text) {
  const tag = 'SYSEDIT_FILE_EOF'
  if (text.includes(tag)) throw new Error(`${path} contains the heredoc tag`)
  return `mkdir -p "$(dirname '${path}')"\ncat > '${path}' <<'${tag}'\n${text}${text.endsWith('\n') ? '' : '\n'}${tag}\n`
}

function scaffold(seed, caseName) {
  const base = mkdtempSync(join(tmpdir(), 'sysedit-scaffold-'))
  cpSync(join(root, 'fixtures', 'storefront'), base, { recursive: true })
  const baseFiles = new Map(listFiles(base).map(f => [f, readFileSync(join(base, f), 'utf8')]))

  const out = [
    '#!/usr/bin/env bash',
    `# Generated by scripts/gen-eval-scaffolds.mjs from ${caseName}/seed.json. Do not edit.`,
    'set -euo pipefail',
    '',
    '# The storefront repository, committed.',
  ]
  for (const [f, text] of baseFiles) out.push(heredoc(f, text))
  out.push(
    'git init -q -b main',
    'git add -A',
    "git -c user.name='Eval' -c user.email='eval@example.com' -c commit.gpgsign=false commit -q -m 'storefront'",
    'HEAD_SHA="$(git rev-parse --short HEAD)"',
    '',
  )

  if (seed.implement) {
    implementFraudCheck(base, { forgetHold: seed.implement === 'forget-hold' })
    out.push(`# Code built for the change (${seed.implement}), not committed.`)
    for (const f of listFiles(base)) {
      const text = readFileSync(join(base, f), 'utf8')
      if (baseFiles.get(f) !== text) out.push(heredoc(f, text))
    }
    out.push('')
  }

  if (seed.model || seed.change) {
    out.push('# System Editor state.')
    const model = { ...goldenModel(), commit: HEAD }
    out.push(heredoc('.sysedit/model.json', JSON.stringify(model, null, 2) + '\n'))
    out.push(heredoc('.sysedit/cache/model-base.json', JSON.stringify(model, null, 2) + '\n'))
    if (seed.change) {
      const cs = buildChange(seed.change)
      out.push(heredoc(`.sysedit/changes/${cs.id}.json`, JSON.stringify(cs, null, 2) + '\n'))
      out.push(heredoc('.sysedit/state.json', JSON.stringify({ activeChange: cs.id }, null, 2) + '\n'))
    }
    out.push(
      '# Stamp the model and change with the real commit, and cache the model under it.',
      `for f in .sysedit/model.json .sysedit/cache/model-base.json .sysedit/changes/*.json; do [ -f "$f" ] && sed -i.bak "s/${HEAD}/$HEAD_SHA/g" "$f" && rm -f "$f.bak"; done`,
      'mv .sysedit/cache/model-base.json ".sysedit/cache/$HEAD_SHA.json"',
      '',
    )
  }
  rmSync(base, { recursive: true, force: true })
  return out.join('\n')
}

const cases = existsSync(evalsDir)
  ? readdirSync(evalsDir).filter(d => existsSync(join(evalsDir, d, 'seed.json')))
  : []
let stale = []
for (const name of cases) {
  const seed = JSON.parse(readFileSync(join(evalsDir, name, 'seed.json'), 'utf8'))
  const text = scaffold(seed, name)
  const target = join(evalsDir, name, 'scaffold.sh')
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== text) stale.push(relative(root, target))
  } else {
    writeFileSync(target, text, { mode: 0o755 })
  }
}
if (check) {
  if (stale.length) {
    console.error(`Stale eval scaffolds (run npm run evals:gen): ${stale.join(', ')}`)
    process.exit(1)
  }
  console.log(`${cases.length} eval scaffold(s) up to date.`)
} else {
  console.log(`Wrote ${cases.length} eval scaffold(s).`)
}
